/**
 * Retourne un sujet aléatoire parmi les 100.
 */
export function getRandomTopic() {
  const idx = Math.floor(Math.random() * REAL_LIFE_100_TOPICS.length);
  return REAL_LIFE_100_TOPICS[idx];
}

/**
 * Retourne deux sujets contrastés pour que Nova propose un choix naturel.
 */
export function getRandomTopicPair() {
  const i1 = Math.floor(Math.random() * REAL_LIFE_100_TOPICS.length);
  let i2 = Math.floor(Math.random() * REAL_LIFE_100_TOPICS.length);
  while (i2 === i1) {
    i2 = Math.floor(Math.random() * REAL_LIFE_100_TOPICS.length);
  }
  return [REAL_LIFE_100_TOPICS[i1], REAL_LIFE_100_TOPICS[i2]];
}

