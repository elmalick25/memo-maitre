/**
 * Génère une amorce orale spontanée, naturelle et variée (évite la répétition systématique de 'introduce yourself').
 */
export function getRandomOpeningGreeting(name, t1, t2) {
  const student = name?.trim() ? name.trim() : "there";
  const greetings = [
    `Hey ${student}! Great to see you. How has your day been going so far? Anything interesting happen today?`,
    `Hey ${student}! Good to connect. I was just thinking about "${t1?.title || "daily adventures"}"—what's your take on that, or is there another topic on your mind today?`,
    `Hey ${student}! How's your energy today? Ready to dive into some lively conversation, or feeling more chill?`,
    `Hey ${student}! What's been keeping you busy lately? Any cool projects, hobbies, or fun stories from this week?`,
    `Hey ${student}! Quick spontaneous question to kick us off: if you could teleport anywhere on the planet right this second, where would you head?`,
    `Hey ${student}! Great to catch up today. We could explore "${t2?.title || "future ambitions"}", or tell me what's been on your mind lately!`,
    `Hey ${student}! How have things been on your side? What's one good thing that put a smile on your face recently?`,
    `Hey ${student}! Welcome back. What's the latest with you? Tell me what you've been working on or thinking about!`
  ];
  return greetings[Math.floor(Math.random() * greetings.length)];
}

